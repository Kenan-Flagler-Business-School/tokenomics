export function calcCost(
  model: LLMModel,
  inputTokens: number,
  outputTokens: number,
  cachedInputTokens = 0
): { inputCost: number; outputCost: number; cachedCost: number; total: number } {
  const inputCost = (inputTokens / 1_000_000) * model.inputPrice;
  const outputCost = (outputTokens / 1_000_000) * model.outputPrice;
  const cachedCost = cachedInputTokens > 0 && model.cachedInputPrice != null
    ? (cachedInputTokens / 1_000_000) * model.cachedInputPrice
    : 0;
  return { inputCost, outputCost, cachedCost, total: inputCost + outputCost + cachedCost };
}
